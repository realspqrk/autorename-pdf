//! `cargo xtask notices [--check]`: write `THIRD_PARTY_NOTICES.md`.
//!
//! Shipped components that are not crates come from `assets/licenses/*.md`
//! (a `@include <path>` line is replaced by that file, relative to the md);
//! the crates of the shipped binary come from cargo-about (`about.toml`,
//! `about.hbs`). `--check` (CI) fails when the committed file is stale.

use std::fs;
use std::path::Path;
use std::process::Command;

use crate::dist::{cargo, exec};

/// The template output depends on the tool; refuse any other version.
const ABOUT_VERSION: &str = "0.9.3";
const OUT: &str = "THIRD_PARTY_NOTICES.md";

const HEADER: &str = "# Third-party notices\n\n\
AutoRename-PDF (MIT, see LICENSE) includes the components below.\n\
Generated by `cargo xtask notices`; do not edit.\n\n\
## Bundled components\n\n";

/// Replace each `@include <path>` line with the file's text.
fn expand_includes(md: &str, dir: &Path) -> Result<String, String> {
    let mut out = String::new();
    for line in md.lines() {
        if let Some(rel) = line.strip_prefix("@include ") {
            let p = dir.join(rel.trim());
            let text = fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()))?;
            out.push_str(text.trim_end());
            out.push('\n');
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    Ok(out)
}

fn manual(root: &Path) -> Result<String, String> {
    let dir = root.join("assets/licenses");
    let mut files: Vec<_> = fs::read_dir(&dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "md"))
        .collect();
    files.sort();
    let mut out = String::new();
    for f in files {
        let text = fs::read_to_string(&f).map_err(|e| format!("{}: {e}", f.display()))?;
        out.push_str(&expand_includes(&text, &dir)?);
        out.push('\n');
    }
    Ok(out)
}

fn ensure_about() -> Result<(), String> {
    let out = Command::new(cargo()).args(["about", "--version"]).output();
    let found = out
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string());
    match found.as_deref().and_then(|t| t.split_whitespace().nth(1)) {
        Some(v) if v == ABOUT_VERSION => Ok(()),
        _ => Err(format!(
            "cargo-about {ABOUT_VERSION} required (found {}): \
             cargo install cargo-about --locked --features cli --version {ABOUT_VERSION}",
            found.as_deref().unwrap_or("none")
        )),
    }
}

/// Placeholders that crates ship in place of their copyright holder (their
/// holders are the authors listed with each crate). Anything else that looks
/// like a placeholder fails the run.
const STUBS: &[&str] = &["<year> <owner>", "<year> <copyright holders>"];
const PLACEHOLDERS: &[&str] = &["<year>", "<owner>", "<copyright holders>"];

fn resolve_stubs(text: &str) -> Result<String, String> {
    let mut out = text.to_string();
    for s in STUBS {
        out = out.replace(s, "the authors listed above");
    }
    match PLACEHOLDERS.iter().find(|p| out.contains(**p)) {
        Some(p) => Err(format!(
            "unresolved placeholder {p} in the crate licenses: add a manual entry in assets/licenses/"
        )),
        None => Ok(out),
    }
}

fn crates(root: &Path) -> Result<String, String> {
    ensure_about()?;
    // Generation is offline: the output must not depend on the network.
    exec(
        Command::new(cargo())
            .current_dir(root)
            .args(["fetch", "--locked"]),
    )?;
    let out = Command::new(cargo())
        .current_dir(root)
        .args([
            "about",
            "generate",
            "--offline",
            "--locked",
            "--fail",
            "-m",
            "crates/app/Cargo.toml",
            "-c",
            "about.toml",
            "about.hbs",
        ])
        .stderr(std::process::Stdio::inherit())
        .output()
        .map_err(|e| format!("cargo about: {e}"))?;
    if !out.status.success() {
        return Err(format!("cargo about failed ({})", out.status));
    }
    resolve_stubs(&String::from_utf8_lossy(&out.stdout))
}

fn lf(s: &str) -> String {
    s.replace("\r\n", "\n")
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let text = lf(&format!("{HEADER}{}{}", manual(root)?, crates(root)?));
    let path = root.join(OUT);
    if check {
        let old = lf(&fs::read_to_string(&path).unwrap_or_default());
        if old != text {
            return Err(format!("{OUT} is stale: run `cargo xtask notices`"));
        }
        println!("{OUT}: up to date");
        return Ok(());
    }
    fs::write(&path, &text).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("{OUT}: written ({} KB)", text.len() / 1024);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn include_lines_are_expanded() {
        let d = std::env::temp_dir().join("xtask-notices-test");
        fs::create_dir_all(&d).unwrap();
        fs::write(d.join("a.txt"), "licence text\n\n").unwrap();
        let out = expand_includes("x\n@include a.txt\ny", &d).unwrap();
        assert_eq!(out, "x\nlicence text\ny\n");
        assert!(expand_includes("@include missing.txt", &d).is_err());
    }

    #[test]
    fn placeholders_are_resolved_or_rejected() {
        let ok = resolve_stubs("Copyright (c) <year> <owner>.").unwrap();
        assert!(!ok.contains('<'));
        assert!(resolve_stubs("Copyright <year> Someone").is_err());
    }

    #[test]
    fn crlf_is_normalized() {
        assert_eq!(lf("a\r\nb\n"), "a\nb\n");
    }
}
